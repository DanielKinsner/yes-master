        let d = decide(Some(&track), Some(&small), true, 0.5);
        assert_eq!(d.correction_db, [0.0; 6]);
        assert!(d.is_active());
        assert!(!d.changes_anything());
        // Gap 0.6 dB at amount 0.5 -> 0.3 dB: kept.
