//! Smart Match: the decision function (Smart Match plan, Slice 3) and its
//! realization as EQ gain (Slice 4).
//!
//! The user picks a reference song; Smart Match closes part of the tonal gap
//! between the track and that reference, band by band, and the Style applies
//! on top as before. [`decide`] is the **decision**: two measured profiles
//! in, six per-band corrections out. [`realize`] turns those six corrections
//! into EQ gains for the chain (contract rule 8).
//!
//! **Inputs, and nothing else (contract rule 1, plan M14).** The track's six
//! band shares, the reference's six band shares, the on/off state and the
//! match amount. The user's EQ, Style, Intensity and Adapt strength never
//! reach this function, so they cannot change the correction.
//!
//! **Profiles, not files (plan M3).** A profile is six shares from
//! [`crate::analysis::compute_spectral_balance_6band`]. Whether they came from
//! a whole file or a short listen makes no difference here.
//!
//! **Order of the rules.** Per band, with `gap` in dB:
//!
//! 1. intended correction = `amount × gap` (rule 3);
//! 2. a boost is faded toward zero when the track's own band sits far below
//!    the library's typical shape (rule 6, plan M16);
//! 3. the result is limited to the caps, and the band is flagged when a cap
//!    changed it (rules 4 and 10);
//! 4. anything smaller than the dead zone becomes exactly zero (rule 5).
//!
//! The fade comes before the caps so that a cap bounds the value that would
//! otherwise be applied, and the "partial" notice means a cap limited the
//! match, not that the track lacks content in that band. The dead zone comes
//! last so no sub-threshold residue survives any earlier step.
//!
//! **Allocation-free and deterministic.** Fixed-size arrays only; no gated
//! static, no I/O. It builds unchanged for desktop, the mobile bridges and the
//! browser engine.

use crate::dsp::BiquadCoeffs;
use crate::types::{EqBandFrequencies, MasteringSettings, SpectralBalance6};
use serde::{Deserialize, Serialize};

/// Number of meter bands.
pub const BAND_COUNT: usize = 6;
/// Machine names of the six meter bands, in meter order.
pub const BAND_KEYS: [&str; BAND_COUNT] = ["sub", "bass", "low_mids", "mids", "presence", "air"];
/// Band edges of the meter, in Hz. The top edge is `min(Nyquist, 16 kHz)`.
pub const BAND_EDGES_HZ: [f64; BAND_COUNT + 1] =
    [20.0, 80.0, 250.0, 800.0, 2500.0, 6500.0, 16_000.0];

/// Shares are floored here before conversion to dB (−90 dB), so an empty band
/// is a very low level rather than minus infinity.
pub const SHARE_FLOOR: f64 = 1.0e-9;

/// Largest cut per band, in dB (plan M8). Lowering it is allowed and logged;
/// raising it needs the owner.
pub const CUT_CAP_DB: f32 = 4.0;
/// Largest boost per band, in dB (plan M8). Same rule as the cut cap.
pub const BOOST_CAP_DB: f32 = 3.0;
/// The match amount a new reference starts at (plan M8). Not tunable.
pub const DEFAULT_AMOUNT: f32 = 0.5;
/// Corrections smaller than this become exactly zero, in dB. Moved from the
/// plan's 0.25 to 0.3 (inside its 0.1–0.5 bounds) so it equals the smallest
/// move the locked result line names ([`NAMED_MOVE_MIN_DB`]): every move the
/// chain makes is then one the text reports (contract rule 11).
pub const DEAD_ZONE_DB: f32 = 0.3;
/// A boost starts to fade when the track's band is this far below the typical
/// shape, in dB.
pub const MISSING_BAND_FADE_START_DB: f32 = 8.0;
/// A boost has faded to zero when the track's band is this far below the
/// typical shape, in dB.
pub const MISSING_BAND_FADE_END_DB: f32 = 14.0;
/// A reference shorter than this is refused (plan parameter table).
pub const REFERENCE_MIN_DURATION_SEC: f64 = 30.0;
/// A reference below this sample rate is refused: the air band would be cut
/// off by Nyquist (plan parameter table).
pub const REFERENCE_MIN_SAMPLE_RATE_HZ: u32 = 32_000;

// The provisional library's typical shape. Generated by the measuring tool
// from the committed statistics; never edited by hand (plan M23).
include!("smart_match_typical_shape.rs");

/// The tunable parameters. [`SmartMatchParams::DEFAULT`] is what the product
/// uses; the evaluation runner may try other values inside the plan's bounds.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct SmartMatchParams {
    pub cut_cap_db: f32,
    pub boost_cap_db: f32,
    pub dead_zone_db: f32,
    pub fade_start_db: f32,
    pub fade_end_db: f32,
}

impl SmartMatchParams {
    pub const DEFAULT: Self = Self {
        cut_cap_db: CUT_CAP_DB,
        boost_cap_db: BOOST_CAP_DB,
        dead_zone_db: DEAD_ZONE_DB,
        fade_start_db: MISSING_BAND_FADE_START_DB,
        fade_end_db: MISSING_BAND_FADE_END_DB,
    };

    /// True when every value is inside the bounds the plan lets the executor
    /// move it within: caps lowered only, dead zone 0.1–0.5 dB, fade start
    /// 6–10 dB and end 12–18 dB below typical.
    pub fn within_plan_bounds(&self) -> bool {
        let in_range = |v: f32, lo: f32, hi: f32| v.is_finite() && v >= lo && v <= hi;
        in_range(self.cut_cap_db, f32::MIN_POSITIVE, CUT_CAP_DB)
            && in_range(self.boost_cap_db, f32::MIN_POSITIVE, BOOST_CAP_DB)
            && in_range(self.dead_zone_db, 0.1, 0.5)
            && in_range(self.fade_start_db, 6.0, 10.0)
            && in_range(self.fade_end_db, 12.0, 18.0)
    }
}

impl Default for SmartMatchParams {
    fn default() -> Self {
        Self::DEFAULT
    }
}

/// Why a decision changes nothing (contract rule 7). The order is the order
/// the checks run in, so the first reason that applies is the one reported.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SmartMatchInactive {
    /// No reference is stored.
    NoReference,
    /// The stored reference's shares are unusable (non-finite, negative or
    /// empty). Only a hand-edited or corrupted project can produce this.
    InvalidReference,
    /// A reference is stored but the match is switched off.
    SwitchedOff,
    /// The match amount is zero (or not a finite number).
    ZeroAmount,
    /// The track's profile is not resolved yet, or this is an Album render
    /// (Album resolves to no profile).
    NoTrackProfile,
    /// The track's shares are unusable.
    InvalidTrack,
}

/// One decision. Every number the user sees is read from here (plan M17).
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct SmartMatchDecision {
    /// `None` when the match is active.
    pub inactive: Option<SmartMatchInactive>,
    /// The amount used, clamped to `[0, 1]`.
    pub amount: f32,
    /// Reference minus track per band, in dB, with the overall offset removed.
    /// Present whenever both profiles are usable, even when the match is off,
    /// so a display can show how far apart the two songs are.
    pub gap_db: Option<[f32; BAND_COUNT]>,
    /// The correction per band in dB: positive boosts, negative cuts. All zero
    /// when inactive.
    pub correction_db: [f32; BAND_COUNT],
    /// Per band: true when a cap changed the correction.
    pub capped: [bool; BAND_COUNT],
    /// True exactly when a cap limited at least one band (contract rule 10).
    pub partial: bool,
}

impl SmartMatchDecision {
    fn inert(reason: SmartMatchInactive, amount: f32, gap_db: Option<[f32; BAND_COUNT]>) -> Self {
        Self {
            inactive: Some(reason),
            amount,
            gap_db,
            correction_db: [0.0; BAND_COUNT],
            capped: [false; BAND_COUNT],
            partial: false,
        }
    }

    /// True when the match is switched on, has a reference, an amount above
    /// zero and a resolved track profile.
    pub fn is_active(&self) -> bool {
        self.inactive.is_none()
    }

    /// True when at least one band would change. When false, the chain must be
    /// exactly as it is without Smart Match (contract rule 9).
    pub fn changes_anything(&self) -> bool {
        self.is_active() && self.correction_db.iter().any(|c| *c != 0.0)
    }
}

/// The decision a chain build uses: the resolved track profile
/// (`settings.advanced.source_profile`; Album resolves to none) and the stored
/// Smart Match state. The chain and the readout both call this, so every
/// number the user sees comes from the computation the audio uses (plan M17).
pub fn decide_for_settings(settings: &MasteringSettings) -> SmartMatchDecision {
    let state = settings.advanced.smart_match.as_ref();
    let track = settings
        .advanced
        .source_profile
        .as_ref()
        .map(|p| &p.spectral_6);
    let reference = state
        .and_then(|s| s.reference.as_ref())
        .map(|r| &r.spectral_6);
    let (enabled, amount) = state.map_or((false, 0.0), |s| (s.enabled, s.amount));
    decide(track, reference, enabled, amount)
}

/// Decide with the product parameters.
pub fn decide(
    track: Option<&SpectralBalance6>,
    reference: Option<&SpectralBalance6>,
    enabled: bool,
    amount: f32,
) -> SmartMatchDecision {
    decide_with(
        &SmartMatchParams::DEFAULT,
        track,
        reference,
        enabled,
        amount,
    )
}

/// Decide with explicit parameters (the evaluation runner's entry point).
pub fn decide_with(
    params: &SmartMatchParams,
    track: Option<&SpectralBalance6>,
    reference: Option<&SpectralBalance6>,
    enabled: bool,
    amount: f32,
) -> SmartMatchDecision {
    let amount = if amount.is_finite() {
        amount.clamp(0.0, 1.0)
    } else {
        0.0
    };
    let track_db = track.and_then(usable_db);
    let reference_db = reference.and_then(usable_db);
    let gap = match (track_db, reference_db) {
        (Some(t), Some(r)) => Some(gap_db(&t, &r)),
        _ => None,
    };
    let gap_f32 = gap.map(|g| g.map(|v| v as f32));

    if reference.is_none() {
        return SmartMatchDecision::inert(SmartMatchInactive::NoReference, amount, None);
    }
    if reference_db.is_none() {
        return SmartMatchDecision::inert(SmartMatchInactive::InvalidReference, amount, None);
    }
    if !enabled {
        return SmartMatchDecision::inert(SmartMatchInactive::SwitchedOff, amount, gap_f32);
    }
    if amount <= 0.0 {
        return SmartMatchDecision::inert(SmartMatchInactive::ZeroAmount, amount, gap_f32);
    }
    if track.is_none() {
        return SmartMatchDecision::inert(SmartMatchInactive::NoTrackProfile, amount, None);
    }
    let (Some(track_db), Some(gap)) = (track_db, gap) else {
        return SmartMatchDecision::inert(SmartMatchInactive::InvalidTrack, amount, None);
    };

    let below_typical = below_typical_db(&track_db);
    let cut_cap = f64::from(params.cut_cap_db.max(0.0));
    let boost_cap = f64::from(params.boost_cap_db.max(0.0));
    let mut correction_db = [0.0_f32; BAND_COUNT];
    let mut capped = [false; BAND_COUNT];
    for b in 0..BAND_COUNT {
        let intended = f64::from(amount) * gap[b];
        let faded = if intended > 0.0 {
            intended * f64::from(boost_fade(params, below_typical[b]))
        } else {
            intended
        };
        let limited = faded.clamp(-cut_cap, boost_cap);
        capped[b] = limited != faded;
        let value = limited as f32;
        correction_db[b] = if value.abs() < params.dead_zone_db {
            0.0
        } else {
            value
        };
    }
    SmartMatchDecision {
        inactive: None,
        amount,
        gap_db: gap_f32,
        correction_db,
        capped,
        partial: capped.iter().any(|c| *c),
    }
}

/// Measure six band shares through the app's own meter, exactly as the
/// track analysis calls it, so a reference and a track are always measured
/// the same way (contract rule 12). `None` for silent or too-short audio.
pub fn measure_shares(
    samples: &[f32],
    sample_rate: u32,
    channels: usize,
) -> Option<SpectralBalance6> {
    crate::analysis::compute_spectral_balance_6band(samples, sample_rate, channels)
}

/// The meter's six shares in band order, widened losslessly to f64.
pub fn shares_array(balance: &SpectralBalance6) -> [f64; BAND_COUNT] {
    [
        f64::from(balance.sub),
        f64::from(balance.low),
        f64::from(balance.low_mid),
        f64::from(balance.mid),
        f64::from(balance.presence),
        f64::from(balance.air),
    ]
}

/// Shares to dB, floored at [`SHARE_FLOOR`].
pub fn shares_to_db(shares: &[f64; BAND_COUNT]) -> [f64; BAND_COUNT] {
    shares.map(|s| 10.0 * s.max(SHARE_FLOOR).log10())
}

/// Median of six values: the mean of the two middle values. NaN-free inputs
/// only (callers check). Allocation-free.
pub fn median6(values: &[f64; BAND_COUNT]) -> f64 {
    let mut sorted = *values;
    sorted.sort_by(f64::total_cmp);
    sorted[2] + (sorted[3] - sorted[2]) * 0.5
}

/// Subtract the median of the six values from each (robust offset removal).
/// A difference in one band then leaves the other five untouched instead of
/// smearing across them.
pub fn remove_offset(values: &[f64; BAND_COUNT]) -> [f64; BAND_COUNT] {
    let offset = median6(values);
    values.map(|v| v - offset)
}

/// Reference minus track per band, in dB, offset removed (contract rule 2).
pub fn gap_db(track_db: &[f64; BAND_COUNT], reference_db: &[f64; BAND_COUNT]) -> [f64; BAND_COUNT] {
    let mut diff = [0.0; BAND_COUNT];
    for (d, (r, t)) in diff.iter_mut().zip(reference_db.iter().zip(track_db)) {
        *d = r - t;
    }
    remove_offset(&diff)
}

/// How far each of the track's bands sits below the library's typical shape,
/// in dB, offset removed. Positive means below typical.
pub fn below_typical_db(track_db: &[f64; BAND_COUNT]) -> [f64; BAND_COUNT] {
    let mut relative = [0.0; BAND_COUNT];
    for (r, (t, typical)) in relative
        .iter_mut()
        .zip(track_db.iter().zip(&TYPICAL_SHAPE_DB))
    {
        *r = t - typical;
    }
    remove_offset(&relative).map(|d| -d)
}

/// The missing-band fade for a boost: 1 at or above the fade start, 0 at or
/// beyond the fade end, linear between (contract rule 6).
pub fn boost_fade(params: &SmartMatchParams, below_typical_db: f64) -> f32 {
    let start = f64::from(params.fade_start_db);
    let end = f64::from(params.fade_end_db);
    if !below_typical_db.is_finite() {
        return 0.0;
    }
    if below_typical_db <= start {
        1.0
    } else if below_typical_db >= end || end <= start {
        0.0
    } else {
        ((end - below_typical_db) / (end - start)) as f32
    }
}

